[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][Alias('Jeu','Rom')][string[]]$Game,
    [string]$MediaRoot = 'G:\Retro\Cartouches\Sega\SG-1000',
    [ValidateSet('Both','Profile','Measure')][string]$Mode = 'Both',
    [ValidateRange(1,100000)][int]$Frames = 120,
    [ValidateRange(0,100000)][int]$WarmupFrames = 2,
    [ValidateSet('Auto','Standard','TheCastle','Othello','Two8KiB')][string]$Layout = 'Auto',
    [ValidateSet('Debug','Release')][string]$Configuration = 'Debug',
    [string]$OutputRoot,
    [string]$CompareTo
)
$ErrorActionPreference = 'Stop'
$Mode = @('Both','Profile','Measure').Where({ $_ -ieq $Mode })[0]
$Layout = @('Auto','Standard','TheCastle','Othello','Two8KiB').Where({ $_ -ieq $Layout })[0]
$repo = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$project = Join-Path $PSScriptRoot 'RetroMediaLab.LocalEmulationTests.csproj'
if ([string]::IsNullOrWhiteSpace($OutputRoot)) { $OutputRoot = Join-Path $repo 'artifacts/TestsMachines/Sega/SG1000/Profiles' }
$OutputRoot = [System.IO.Path]::GetFullPath($OutputRoot)
if (-not [string]::IsNullOrWhiteSpace($CompareTo)) { $CompareTo = (Get-Item -LiteralPath $CompareTo).FullName }
$resolvedGames = foreach ($selected in $Game) {
    $candidate = if ([System.IO.Path]::IsPathRooted($selected)) { $selected } else { Join-Path $MediaRoot $selected }
    if (-not [System.IO.Path]::HasExtension($candidate)) { $candidate += '.sg' }
    (Get-Item -LiteralPath $candidate).FullName
}
$traceTool = (Get-Command dotnet-trace -CommandType Application -ErrorAction Stop).Source
$toolStore = Join-Path (Split-Path -Parent $traceTool) '.store/dotnet-trace'
$client = Get-ChildItem -LiteralPath $toolStore -Recurse -File -Filter 'Microsoft.Diagnostics.NETCore.Client.dll' |
    Sort-Object LastWriteTimeUtc -Descending | Select-Object -First 1
if ($null -eq $client) { throw 'The installed dotnet-trace diagnostics library was not found.' }
$entry = Join-Path $PSScriptRoot 'Emulation/Sega/Sg1000RequestedProfile.Generated.cs'
if (Test-Path -LiteralPath $entry) { throw "A generated profiling entry already exists: $entry" }
[System.IO.Directory]::CreateDirectory($OutputRoot) | Out-Null
$requestPath = Join-Path $OutputRoot ('request-' + [guid]::NewGuid().ToString('N') + '.json')
$request = @{
    Games = @($resolvedGames); OutputRoot = $OutputRoot; DiagnosticClientPath = $client.FullName
    TraceToolPath = $traceTool; Mode = $Mode; Frames = $Frames; WarmupFrames = $WarmupFrames
    Layout = $Layout; CompareTo = $CompareTo
}
$generatedSource = @'
// Generated by Profile-Sg1000.ps1; removed in the launcher's finally block.
using System;
using System.Linq;
using System.Threading.Tasks;
using Xunit;
using Xunit.Abstractions;
namespace RetroMediaLab.Tests.Emulation.Sega;
public sealed class Sg1000RequestedProfile(ITestOutputHelper output)
{
    [Fact]
    public async Task ProfileSelectedGames()
    {
        var reports = await Sg1000Profiling.RunRequestedAsync(
            Environment.GetEnvironmentVariable("RML_SG_PROFILE_REQUEST")
                ?? throw new InvalidOperationException("Missing profiling request."), output.WriteLine);
        Assert.True(reports.All(report => report.Status == "Completed"),
            string.Join(Environment.NewLine, reports.Where(report => report.Status != "Completed")
                .Select(report => report.Rom + ": " + report.Error)));
    }
}
'@
$oldRequest = $env:RML_SG_PROFILE_REQUEST
$exitCode = 1
try {
    [System.IO.File]::WriteAllText($requestPath, ($request | ConvertTo-Json -Depth 4))
    [System.IO.File]::WriteAllText($entry, $generatedSource)
    $env:RML_SG_PROFILE_REQUEST = $requestPath
    Write-Host "SG-1000: $Mode, $Frames frames, results in $OutputRoot"
    & dotnet test $project -c $Configuration --no-restore --filter 'FullyQualifiedName~Sg1000RequestedProfile' `
        --logger 'console;verbosity=normal' --logger 'trx;LogFileName=profile.trx' `
        --results-directory (Join-Path $OutputRoot ('TestRun-' + [guid]::NewGuid().ToString('N')))
    $exitCode = $LASTEXITCODE
}
finally {
    $env:RML_SG_PROFILE_REQUEST = $oldRequest
    if (Test-Path -LiteralPath $entry) {
        if ([System.IO.File]::ReadAllText($entry) -ne $generatedSource) { throw 'Generated entry changed during the run; cleanup refused.' }
        [System.IO.File]::Delete($entry)
    }
    [System.IO.File]::Delete($requestPath)
}
exit $exitCode
